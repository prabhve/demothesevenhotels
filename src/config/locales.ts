export const getLocaleList = (): LocaleConfig[] => Object.values(localesRegistry);

export const getIndexableLocales = (): LocaleConfig[] =>
  Object.values(localesRegistry).filter((l) => l.isIndexable);

export const getLocaleByCode = (code: string): LocaleConfig => {
  const normalized = code.toLowerCase().trim();
  return localesRegistry[normalized] || localesRegistry[DEFAULT_LOCALE_CODE];
};
