/**
 * Centralized Locale Registry
 * Supports Indian & International Languages with LTR/RTL support,
 * localized formatting, currency estimations, and indexation controls.
 */

export type TextDirection = 'ltr' | 'rtl';
export type LocaleGroup = 'core' | 'indian' | 'international';

export interface LocaleConfig {
  code: string;               // e.g. 'en', 'hi', 'zh-hans'
  locale: string;             // BCP 47 tag, e.g. 'en-IN', 'hi-IN', 'ar-SA'
  languageCode: string;       // ISO 639-1 e.g. 'en', 'hi'
  regionCode: string;         // ISO 3166-1 alpha-2 e.g. 'IN', 'FR'
  nativeName: string;         // e.g. 'हिन्दी', 'বাংলা', 'العربية'
  englishName: string;        // e.g. 'Hindi', 'Bengali', 'Arabic'
  direction: TextDirection;   // 'ltr' or 'rtl'
  urlPrefix: string;          // '/en', '/hi', etc.
  currency: string;           // 'INR', 'USD', 'EUR', etc.
  currencySymbol: string;     // '₹', '$', '€', etc.
  approxExchangeRateToInr?: number; // 1 Foreign Currency = X INR (approximate, for reference only)
  dateFormat: string;
  timeFormat: string;
  group: LocaleGroup;
  isIndexable: boolean;       // Set true when full translation passes quality & completeness check
  isComplete: boolean;
}

